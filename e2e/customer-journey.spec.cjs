const { test, expect } = require('@playwright/test');
test('dairy edits customer details, customer claims history and sees only the customer portal', async ({ page, request }) => {
  const base = 'http://127.0.0.1:4001/api', stamp = Date.now();
  const email = `claim-${stamp}@example.com`, ownerEmail = `dairy-${stamp}@example.com`, password = 'Local-browser-password';
  const issued = await request.post(base + '/auth/register', { data: { name: 'Portal Owner', businessName: 'Portal Test Dairy', phone: '9876543210', email: ownerEmail, password } });
  expect(issued.status()).toBe(202);
  const verified = await request.post(base + '/auth/verify', { data: { email: ownerEmail, otp: (await issued.json()).data.developmentOtp } });
  const vendor = (await verified.json()).data, auth = { Authorization: `Bearer ${vendor.token}` };
  const customer = await request.post(base + '/customers', { headers: auth, data: { name: 'Existing Customer', email, phone: '9876543210', address: 'First address', startDate: '2025-01-01', cowRatePaise: 6000, buffaloRatePaise: 8000 } });
  expect(customer.status()).toBe(201); const customerId = (await customer.json()).data._id;
  expect((await request.post(base + '/records/batch', { headers: { ...auth, 'Idempotency-Key': `history-${stamp}` }, data: { items: [{ customer_id: customerId, date: '2025-01-15', shift: 'morning', type: 'cow', quantityMl: 1500 }] } })).status()).toBe(201);
  await page.goto('/');
  await page.getByLabel('Email address').fill(ownerEmail); await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('link', { name: 'Customers', exact: true }).click();
  await page.getByRole('button', { name: 'Edit customer', exact: true }).click();
  await page.getByLabel('Cow rate (₹ / litre)').fill('75');
  await page.getByRole('button', { name: 'Save customer', exact: true }).click();
  await expect(page.getByText('Customer updated. Existing delivery rates were preserved.')).toBeVisible();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.getByRole('button', { name: 'I’m a customer — join my dairy' }).click();
  await page.getByLabel('Dairy code').fill(vendor.user.code);
  await page.getByRole('button', { name: 'Find dairy', exact: true }).click();
  await expect(page.getByText('Portal Test Dairy', { exact: true })).toBeVisible();
  await page.getByLabel('Your name', { exact: true }).fill('Customer Verified');
  await page.getByLabel('Phone number').fill('9876543210');
  await page.getByLabel('Email address').fill(email); await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Verify my email' }).click();
  const code = (await page.getByText(/Local development code:/).textContent()).match(/\d{6}/)[0];
  await page.getByLabel('Verification code').fill(code);
  await page.getByRole('button', { name: 'Verify & get started' }).click();
  await page.getByRole('radio', { name: /Claim Existing Customer/ }).check();
  await page.getByRole('button', { name: 'Confirm & connect' }).click();
  await expect(page.getByRole('heading', { name: 'Hello, Existing.' })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Customers', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'Delivery history', exact: true }).first().click();
  await expect(page.getByRole('cell', { name: '₹90.00', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: '₹60.00', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Save deliveries' })).toHaveCount(0);
  await page.getByRole('link', { name: 'Your profile', exact: true }).first().click();
  await page.getByLabel('Your name', { exact: true }).fill('Updated Customer');
  await page.getByLabel('Delivery address').fill('Updated address');
  await page.getByRole('button', { name: 'Save profile' }).click();
  await expect(page.getByText('Your profile has been updated.')).toBeVisible();
  await page.getByRole('link', { name: 'Bills & payments', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your bills & payments' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Generate bill' })).toHaveCount(0);
});
