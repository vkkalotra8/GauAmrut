const { test, expect } = require('@playwright/test');
test('desktop demo dashboard and mobile directory remain usable', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.goto('/');
  await page.getByRole('button', { name: /Explore the demo/ }).click();
  await expect(page.getByRole('heading', { name: 'A fresh day, Aarav.' })).toBeVisible();
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true });
  await page.getByRole('link', { name: 'Customers', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search customers' }).fill('Meera');
  await expect(page.getByRole('heading', { name: 'Meera Shah' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Rajesh Patel' })).toHaveCount(0);
  await page.setViewportSize({ width: 375, height: 812 });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.locator('aside.sidebar').getByRole('link', { name: 'Overview' }).click();
  await expect(page.getByRole('heading', { name: 'A fresh day, Aarav.' })).toBeVisible();
  await page.screenshot({ path: 'test-results/dashboard-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 320, height: 720 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
